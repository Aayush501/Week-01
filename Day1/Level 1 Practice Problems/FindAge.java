// Defining public class FindAge, which contains main() method

public class FindAge {
	
	// difining the main() method
	public static void main(String[] args){
		
		// created two integer variables birthYear and currentYear 
		// birthYear represents birth year of Harry and currentYear represents the current year
	
		int birthYear =  2000, currentYear = 2024;
	
		// calculating the age of Harry and storing the result into an integer variable ageOfHarry
	
		int ageOfHarry = currentYear - birthYear;
	
		// displaying the output 
	
		System.out.println("Harry's age in 2024 is "+ ageOfHarry);
	
	}
	
}